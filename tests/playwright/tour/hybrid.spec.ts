test('escribir, abrir formularios y cerrar no completar una guía', async ({ page }, info) => {
  const { errors } = await setupDashboard(page)
  await page.goto('/dashboard?tab=collab')
  await startTour(page, 'Misión 1: Exploración del Tablero Kanban')
  const guide = page.getByTestId('tour-guide')
  const search = page.locator('[data-tour="collab-search"]').locator('input').or(page.locator('input[data-tour="collab-search"]')).first()
  await search.fill('Texto sin resultados')
  await search.press('Enter')
  await expect(search).toBeFocused()
  await expect(guide).toContainText('Paso 1 de 5')
  await assertBounds(page)
  await guide.getByRole('button', { name: 'Minimizar tutorial' }).click()
  await expect(guide.getByRole('heading')).toHaveCount(0)
  await guide.getByRole('button', { name: 'Expandir tutorial' }).click()
  await search.fill('')
  for (let step = 2; step <= 4; step++) {
    await guide.getByRole('button', { name: 'Siguiente', exact: true }).click()
    await expect(guide).toContainText(`Paso ${step} de 5`)
    await expect(guide).toHaveAttribute('aria-busy', 'false')
  }
  await page.locator('[data-tour="collab-create-btn"]').click()
  const form = page.getByRole('dialog').filter({ hasNot: page.getByText('Centro de ayuda', { exact: true }) })
  await expect(form).toBeVisible()
  await expect(guide).toHaveCount(0)
  await form.getByRole('button', { name: /cerrar|cancelar/i }).first().click()
  await expect(guide).toContainText('Paso 4 de 5')
  await assertBounds(page)
  await page.screenshot({ path: info.outputPath('hybrid.png'), fullPage: true })
  await guide.getByRole('button', { name: 'Cerrar tutorial' }).click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('cima_tour_v2:tutorial%40example.com') ?? '[]'))).toEqual([])
  expect(errors).toEqual([])
})

