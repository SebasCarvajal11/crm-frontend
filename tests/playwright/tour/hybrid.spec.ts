for (const role of ['admin', 'worker', 'client'] as const) {
  for (const tour of ALL_TOURS.filter((tour) => tour.roles.includes(role))) {
    test(`recorrer guía autorizada y finalizar explícitamente: ${role} / ${tour.id}`, async ({ page }, info) => {
      const { errors, mutations } = await setupDashboard(page, role)
      const unavailable: string[] = []
      await page.goto('/dashboard?tab=collab')
      await startTour(page, tour.title)
      const guide = page.getByTestId('tour-guide')
      const steps = tour.steps.filter((step) => !step.requiredRole || step.requiredRole.includes(role))
      for (let index = 0; index < steps.length; index++) {
        await expect(guide).toHaveAttribute('aria-busy', 'false')
        await expect(guide.getByRole('heading')).toHaveText(steps[index].title)
        if (await guide.getByRole('button', { name: 'Volver al paso' }).isVisible()) unavailable.push(steps[index].element)
        await assertBounds(page)
        await guide.getByRole('button', { name: index === steps.length - 1 ? 'Finalizar' : /Siguiente|Omitir paso/, exact: true }).click()
      }
      await expect(guide).toHaveCount(0)
      expect(errors).toEqual([])
      await info.attach('unavailable-targets', { body: JSON.stringify([...new Set(unavailable)], null, 2), contentType: 'application/json' })
      const conditionalTargets = [
        '[data-tour="admin-file-project-header"]', '[data-tour="admin-file-folder-tabs"]',
        '[data-tour="admin-file-table"]', '[data-tour="admin-user-actions"]',
        '[data-tour="account-sessions-revoke-btn"]',
        '[data-tour="workspace-files-panel"]', '[data-tour="workspace-timeline-panel"]',
      ]
      expect([...new Set(unavailable)].filter((selector) => !conditionalTargets.includes(selector))).toEqual([])
      expect(mutations.filter((request) => !request.endsWith('/read'))).toEqual([])
    })
  }
}

test('zoom, teclado, pantalla reducida y reinicio sin trabajo asíncrono residual', async ({ page }, info) => {
  const { errors } = await setupDashboard(page, 'worker')
  await page.addInitScript(() => localStorage.setItem('cima_ui_zoom', '1.5'))
  await page.goto('/dashboard?tab=collab')
  await startTour(page, 'Misión 1: Exploración del Tablero Kanban')
  const guide = page.getByTestId('tour-guide')
  await assertBounds(page)
  await page.setViewportSize({ width: Math.min(page.viewportSize()!.width, 768), height: 420 })
  await assertBounds(page)
  await page.screenshot({ path: info.outputPath('short-viewport-zoom.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 260 })
  await expect(guide.getByRole('heading')).toHaveCount(0)
  await expect(guide).toContainText('Paso 1 de 4')
  await assertBounds(page)
  await page.setViewportSize({ width: 390, height: 420 })
  await expect(guide.getByRole('heading')).toHaveText('Buscador de Proyectos')
  await guide.getByRole('button', { name: 'Mostrar elemento', exact: true }).click()
  await expect.poll(() => page.locator('.cima-tour-highlight').evaluate((element) => element.getBoundingClientRect().height > 0)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(guide).toHaveCount(0)
  await startTour(page, 'Misión 2: Flujo de Tareas Operativas')
  await guide.getByRole('button', { name: 'Cerrar tutorial' }).click()
  await startTour(page, 'Recorrido del Centro de Notificaciones')
  await expect(guide.getByRole('heading')).toHaveText('Bandeja de Novedades')
  await page.waitForURL(/tab=notifications/)
  await expect(guide).toHaveAttribute('aria-busy', 'false')
  await guide.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(guide.getByRole('heading')).toHaveText('Actualizar Notificaciones')
  await expect(guide).toHaveAttribute('aria-busy', 'false')
  await page.evaluate(() => window.dispatchEvent(new Event('resize')))
  await expect(guide.getByRole('heading')).toHaveText('Actualizar Notificaciones')
  expect(errors).toEqual([])
})

