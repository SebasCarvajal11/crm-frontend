  await page.screenshot({ path: info.outputPath('help-center.png'), fullPage: true })
  await expect(page.getByRole('dialog')).toContainText('Completado')
  await page.reload()
  await openHelp(page)
  await expect(page.getByRole('dialog')).toContainText('Completado')
